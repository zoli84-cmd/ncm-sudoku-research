MINUS = r"\ensuremath{-}"


def _signed(text: str) -> str:
    if text.startswith("-"):
        body = text[1:]
        return body if set(body) <= {"0", "."} else MINUS + body
    return text


def fmt(x, kind: str) -> str:
    """Format a stored value; kinds: pp1, pp1abs, pct1 (x100, 1 decimal), pct0, dec1, dec2, dec4, sig2, g, int."""
    if kind == "commit" and isinstance(x, str) and len(x) >= 7:
        return x[:7]
    if x is None or isinstance(x, bool) or (isinstance(x, float) and math.isnan(x)):
        raise ValueError(f"cannot format {x!r}")
    if kind == "pp1abs":  # magnitude for prose such as "lowered by X points"
        return f"{100 * abs(x):.1f}"
    if kind in ("pp1", "pct1"):
        return _signed(f"{100 * x:.1f}")
    if kind == "dec1":
        return _signed(f"{x:.1f}")
    if kind == "dec2":
        return _signed(f"{100 * x:.2f}") if abs(x) <= 1 else _signed(f"{x:.2f}")
    if kind == "dec4":
        return _signed(f"{x:.4f}")
    if kind == "sig2":
        if x == 0:
            return "0"
        digits = max(0, 1 - math.floor(math.log10(abs(x))))
        return _signed(f"{x:.{digits}f}")
    if kind == "pct0":
        return _signed(f"{100 * x:.0f}")
    if kind == "g":  # plan constants: shortest exact decimal
        return _signed(f"{x:g}")
    if kind == "int":
        if int(x) != x:
            raise ValueError(f"not an integer: {x!r}")
        return str(int(x))
    raise ValueError(f"unknown format kind {kind!r}")


_SELECT = re.compile(r"^(?P<name>[^\[]+)\[(?P<cond>[^\]]+)\]$")


def _matches(item: dict, cond: str) -> bool:
    """`k=v,k=v`: every field's string form equals the value (`row=wl_L06.generated`, `level=6,dose=13`)."""
    pairs = [c.split("=", 1) for c in cond.split(",")] if "row=" not in cond else [cond.split("=", 1)]
    return all(str(item.get(k)) == v for k, v in pairs)


def _parts(path: str) -> list[str]:
    parts, depth, cur = [], 0, ""
    for ch in path:
        if ch == "." and depth == 0:
            parts.append(cur)
            cur = ""
            continue
        depth += ch == "["
        depth -= ch == "]"
        cur += ch
    parts.append(cur)
    return parts


def lookup(doc, path: str):
    """Dotted path; integer components index lists; `name[k=v,...]` selects the one list item matching all fields."""
    cur = doc
    parts = _parts(path)
    i = 0
    while i < len(parts):
        part = parts[i]
        m = _SELECT.match(part)
        try:
            if m:
                cur = next(item for item in cur[m["name"]] if _matches(item, m["cond"]))
            elif isinstance(cur, list):
                cur = cur[int(part)]
            else:
                # dict keys may contain dots (`wl_L06.generated`): take the shortest key that exists
                j = i
                while part not in cur and j + 1 < len(parts):
                    j += 1
                    part = part + "." + parts[j]
                cur = cur[part]
                i = j
        except (KeyError, IndexError, TypeError, ValueError, StopIteration):
            raise KeyError(path) from None
        i += 1
    return cur


def _contrast(key: str, path: str, kind: str, family: bool = False, tost: bool = False) -> dict:
    out = {
        f"{key}.est": ("results", f"{path}.estimate", kind),
        f"{key}.ci.lo": ("results", f"{path}.ci95.ci.0", kind),
        f"{key}.ci.hi": ("results", f"{path}.ci95.ci.1", kind),
        f"{key}.n": ("results", f"{path}.n", "int"),
        f"{key}.nnz": ("results", f"{path}.n_nonzero", "int"),
    }
    if family:
        out[f"{key}.fam.lo"] = ("results", f"{path}.family.ci.0", kind)
        out[f"{key}.fam.hi"] = ("results", f"{path}.family.ci.1", kind)
    if tost:
        out[f"{key}.tost.lo"] = ("results", f"{path}.tost.ci.0", kind)
        out[f"{key}.tost.hi"] = ("results", f"{path}.tost.ci.1", kind)
    return out


