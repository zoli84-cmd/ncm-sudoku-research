KEYS = _keys()


def load_sources(root: Path) -> dict[str, dict]:
    sources = {name: json.loads((root / rel).read_text(encoding="utf-8")) for name, rel in SOURCE_FILES.items()}
    sources["design"] = dict(DESIGN)
    sources["plan"] = {
        "h1margin": H1_MARGIN, "theta2pmargin": THETA2P_MARGIN, "thetaTmargin": THETA_T_MARGIN,
        "equivtol": EQUIV_TOLERANCE, "h2practical": H2_PRACTICAL, "h3practical": H3_PRACTICAL,
    }
    return sources


def collect(sources: dict[str, dict]) -> dict[str, str]:
    out = {}
    for key, (source, path, kind) in KEYS.items():
        value = lookup(sources[source], path)
        try:
            out[key] = fmt(value, kind)
        except ValueError as e:
            raise ValueError(f"{key} ({source}:{path}): {e}") from None
    return out


def numbers_tex(numbers: dict[str, str]) -> str:
    return TEX_HEADER + "".join(f"\\wpdef{{{k}}}{{{v}}}\n" for k, v in sorted(numbers.items()))


def numbers_json(numbers: dict[str, str]) -> str:
    return json.dumps(dict(sorted(numbers.items())), indent=1, ensure_ascii=False) + "\n"
